# Object Detection

from ultralytics import YOLO

# 1. Load pre-trained YOLO model
model = YOLO("yolov8n.pt")   # small & fast model

# 2. Run object detection on an image
results = model("/content/doggo.jpg")  # put image in same folder

# 3. Show detection result
results[0].show()

# Pre-trained models (like YOLO) can detect only the object classes they were trained on.

#For example:
# Person, Car, Dog, Cat, Bicycle, Chair

#These come from a fixed list of classes. and also this model is trained on COCO model which has 80 classes.

# Input video file
input_video = "/content/10 seconds with the Cutest Dog on Youtube! #Shorts.mp4"

# Output video file
output_video = "DOG_video.mp4"

# Run object detection on video
results = model.predict(
    source=input_video,     # input video
    save=True,              # save annotated video
    device ="cpu",             # show frames in real time
    conf=0.5                # confidence threshold
)

for result in results:
  print(result.boxes)
  print(result.boxes.cls)
  print(result.boxes.conf)

print(f" Output saved as {output_video}")

